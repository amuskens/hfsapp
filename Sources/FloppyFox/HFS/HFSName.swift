import Foundation

/// A classic HFS file or volume name: up to 31 (volumes: 27) raw Mac Roman bytes. Kept as bytes
/// rather than a `String` so names round-trip exactly, including bytes with no Unicode mapping.
struct HFSName: Hashable, Sendable, CustomStringConvertible {
    static let maxLength = 31
    static let maxVolumeLength = 27

    let bytes: [UInt8]

    init(bytes: [UInt8]) {
        self.bytes = bytes
    }

    /// Fails for names that can't exist on HFS: empty, too long, containing `:` (the path
    /// separator), or characters outside Mac Roman.
    init(_ string: String, maxLength: Int = HFSName.maxLength) throws {
        guard !string.isEmpty,
              let data = string.precomposedStringWithCanonicalMapping.data(using: .macOSRoman, allowLossyConversion: false),
              !data.isEmpty, data.count <= maxLength, !data.contains(UInt8(ascii: ":")) else {
            throw HFSError.invalidName(string)
        }
        self.bytes = Array(data)
    }

    var string: String {
        String(data: Data(bytes), encoding: .macOSRoman) ?? String(decoding: bytes, as: UTF8.self)
    }

    var description: String { string }

    /// Classic Mac OS name ordering: case-insensitive, diacritic-sensitive, per the ordering
    /// table below. A shorter name that is a prefix of a longer one sorts first.
    static func compare(_ lhs: [UInt8], _ rhs: [UInt8]) -> Int {
        for (a, b) in zip(lhs, rhs) {
            let diff = Int(sortOrder[Int(a)]) - Int(sortOrder[Int(b)])
            if diff != 0 { return diff }
        }
        return lhs.count - rhs.count
    }

    /// True when the two names are the same name as far as the Finder is concerned.
    func matches(_ other: HFSName) -> Bool {
        Self.compare(bytes, other.bytes) == 0
    }

    /// Sort weight of each Mac Roman byte in Mac OS's catalog order (the Toolbox's RelString
    /// with case-insensitive, diacritic-sensitive comparison). Lowercase letters share their
    /// uppercase letter's weight; accented letters sort right after their base letter.
    /// Verified against Apple's `fsck_hfs`, which rejects catalogs whose keys are out of order
    /// (see `HFSEngineTests.testNameOrderMatchesApplesCatalogChecker`).
    static let sortOrder: [UInt8] = [
        // 0x00 control characters
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F,
        // 0x20 space ! " # $ % & ' ( ) * + , - . /  then 0-9 : ; < = > ?
        0x20, 0x22, 0x23, 0x28, 0x29, 0x2A, 0x2B, 0x2C, 0x2F, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36,
        0x37, 0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46,
        // 0x40 @ A-Z [ \ ] ^ _
        0x47, 0x48, 0x58, 0x5A, 0x5E, 0x60, 0x67, 0x69, 0x6B, 0x6D, 0x73, 0x75, 0x77, 0x79, 0x7B, 0x7F,
        0x8D, 0x8F, 0x91, 0x93, 0x96, 0x98, 0x9F, 0xA1, 0xA3, 0xA5, 0xA8, 0xAA, 0xAB, 0xAC, 0xAD, 0xAE,
        // 0x60 ` a-z (same weights as A-Z) { | } ~ DEL
        0x54, 0x48, 0x58, 0x5A, 0x5E, 0x60, 0x67, 0x69, 0x6B, 0x6D, 0x73, 0x75, 0x77, 0x79, 0x7B, 0x7F,
        0x8D, 0x8F, 0x91, 0x93, 0x96, 0x98, 0x9F, 0xA1, 0xA3, 0xA5, 0xA8, 0xAF, 0xB0, 0xB1, 0xB2, 0xB3,
        // 0x80 Ä Å Ç É Ñ Ö Ü á à â ä ã å ç é è  ê ë í ì î ï ñ ó ò ô ö õ ú ù û ü
        0x4C, 0x50, 0x5C, 0x62, 0x7D, 0x81, 0x9A, 0x55, 0x4A, 0x56, 0x4C, 0x4E, 0x50, 0x5C, 0x62, 0x64,
        0x65, 0x66, 0x6F, 0x70, 0x71, 0x72, 0x7D, 0x89, 0x8A, 0x8B, 0x81, 0x83, 0x9C, 0x9D, 0x9E, 0x9A,
        // 0xA0 † ° ¢ £ § • ¶ ß ® © ™ ´ ¨ ≠ Æ Ø  ∞ ± ≤ ≥ ¥ µ ∂ ∑ ∏ π ∫ ª º Ω æ ø
        0xB4, 0xB5, 0xB6, 0xB7, 0xB8, 0xB9, 0xBA, 0x95, 0xBB, 0xBC, 0xBD, 0xBE, 0xBF, 0xC0, 0x52, 0x85,
        0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0xCA, 0xCB, 0x57, 0x8C, 0xCC, 0x52, 0x85,
        // 0xC0 ¿ ¡ ¬ √ ƒ ≈ ∆ « » … nbsp À Ã Õ Œ œ  – — “ ” ‘ ’ ÷ ◊ ÿ Ÿ ⁄ € ‹ › ﬁ ﬂ
        0xCD, 0xCE, 0xCF, 0xD0, 0xD1, 0xD2, 0xD3, 0x26, 0x27, 0xD4, 0x20, 0x4A, 0x4E, 0x83, 0x87, 0x87,
        0xD5, 0xD6, 0x24, 0x25, 0x2D, 0x2E, 0xD7, 0xD8, 0xA7, 0xD9, 0xDA, 0xDB, 0xDC, 0xDD, 0xDE, 0xDF,
        // 0xE0 and up: no special ordering
        0xE0, 0xE1, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0xEA, 0xEB, 0xEC, 0xED, 0xEE, 0xEF,
        0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9, 0xFA, 0xFB, 0xFC, 0xFD, 0xFE, 0xFF,
    ]
}
